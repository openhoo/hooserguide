// Render the GitHub Wiki from repository Markdown. No network access is needed.
import { mkdir, readFile, readdir, realpath, stat, writeFile, rm } from 'node:fs/promises';
import { dirname, join, relative, resolve, isAbsolute, sep } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { parseArgs } from 'node:util';
import { parsers } from 'prettier/plugins/markdown';

const sourceRoot = fileURLToPath(new URL('../', import.meta.url));
const marker = '<!-- Generated by hooserguide scripts/wiki.mjs from ';
const inRoot = (root, file) => {
  const path = relative(root, file);
  return path !== '..' && !path.startsWith('..' + sep) && !isAbsolute(path);
};
const slugNames = new Map([
  ['integration', 'Integrations'],
  ['gitlab', 'GitLab'],
]);
const pageSlug = (name) =>
  slugNames.get(name) ??
  name.replace(/(^|-)([a-z])/g, (_, prefix, letter) => prefix + letter.toUpperCase());
const flatten = (node) => node.children?.map(flatten).join('') ?? node.value ?? node.alt ?? '';
function* walk(node) {
  yield node;
  for (const child of node.children ?? []) yield* walk(child);
}
function headings(tree) {
  const ids = new Set();
  for (const node of walk(tree)) {
    if (node.type !== 'heading') continue;
    const base = flatten(node)
      .toLowerCase()
      .replace(/[^\p{L}\p{N}\p{M}_ -]/gu, '')
      .replaceAll(' ', '-');
    let id = base;
    for (let i = 1; ids.has(id); i++) id = base + '-' + i;
    ids.add(id);
  }
  return ids;
}

// Use the Markdown AST for locations so examples, fenced code and inline code remain byte-for-byte intact.
// Within an actual link node, replace only the destination, preserving its label and optional title.
function destinationRange(source, node) {
  const start = node.position.start.offset;
  const text = source.slice(start, node.position.end.offset);
  let i = node.type === 'image' ? 1 : 0;
  if (text[i] !== '[') return;
  let depth = 1;
  const lastChild = node.children?.at(-1);
  if (lastChild) {
    i = lastChild.position.end.offset - start;
    depth = 0;
  }
  for (i++; i < text.length && depth; i++) {
    if (text[i] === '\\') i++;
    else if (text[i] === '[') depth++;
    else if (text[i] === ']') depth--;
  }
  if (text[i++] !== (node.type === 'definition' ? ':' : '(')) return;
  while (/\s/.test(text[i] ?? '')) i++;
  const from = i;
  if (text[i] === '<') {
    while (++i < text.length && text[i] !== '>') {
      if (text[i] === '\\') i++;
    }
    i++;
  } else {
    for (let nesting = 0; i < text.length; i++) {
      if (text[i] === '\\') i++;
      else if (text[i] === '(') nesting++;
      else if (text[i] === ')') {
        if (nesting === 0) break;
        nesting--;
      } else if (/\s/.test(text[i])) break;
    }
  }
  return [start + from, start + i];
}

export async function renderWiki({
  root = sourceRoot,
  repo = 'openhoo/hooserguide',
  ref = 'main',
} = {}) {
  root = await realpath(root);
  if (!/^[\w.-]+\/[\w.-]+$/.test(repo) || repo.split('/').some((s) => s === '.' || s === '..'))
    throw Error('Expected --repo owner/name');
  if (!/^[\w-][\w.-]*$/.test(ref))
    throw Error('Use a commit SHA, tag or simple branch name for --ref');
  const web = 'https://github.com/' + repo;
  const pages = new Map(),
    bySlug = new Map();
  for (const folder of ['docs', 'docs/wiki']) {
    for (const entry of (await readdir(join(root, folder), { withFileTypes: true })).sort((a, b) =>
      a.name < b.name ? -1 : a.name > b.name ? 1 : 0,
    )) {
      if (!entry.isFile() || !entry.name.endsWith('.md')) continue;
      const stem = entry.name.slice(0, -3);
      if (!/^[A-Za-z_][\w-]*$/.test(stem))
        throw Error('Wiki sources require simple filenames: ' + entry.name);
      const path = folder + '/' + entry.name,
        slug = pageSlug(stem);
      if (bySlug.has(slug.toLowerCase())) throw Error('Duplicate wiki page: ' + slug);
      const source = await readFile(join(root, path), 'utf8');
      const tree = await parsers.markdown.parse(source);
      const page = { path, slug, source, tree, anchors: headings(tree) };
      pages.set(path, page);
      bySlug.set(slug.toLowerCase(), page);
    }
  }
  if (!pages.has('docs/wiki/Home.md') || !pages.has('docs/wiki/_Sidebar.md'))
    throw Error('Wiki requires Home.md and _Sidebar.md');
  const files = new Map();
  async function urlFor(url, page, line, image = false) {
    const where = page.path + ':' + line;
    const fail = (msg) => {
      throw Error(where + ': ' + msg + ': ' + url);
    };
    let targetPage, target, fragment, query;
    if (/^[a-z][a-z0-9+.-]*:/i.test(url) || url.startsWith('//')) {
      if (!url.startsWith(web + '/wiki/')) return url;
      const parsed = new URL(url);
      targetPage = bySlug.get(
        decodeURIComponent(parsed.pathname.slice(('/' + repo + '/wiki/').length)).toLowerCase(),
      );
      if (!targetPage) fail('Unknown wiki page');
      fragment = parsed.hash;
      query = parsed.search;
    } else {
      const [, path, search, hash] = /^([^?#]*)(\?[^#]*)?(#.*)?$/.exec(url);
      query = search ?? '';
      fragment = hash ?? '';
      if (path.startsWith('/')) fail('Use a repository-relative target or a full URL');
      target = resolve(
        root,
        dirname(page.path),
        decodeURIComponent(path || page.path.split('/').at(-1)),
      );
      if (!inRoot(root, target)) fail('Link escapes repository');
      const actual = await realpath(target).catch(() => fail('Missing link target'));
      if (!inRoot(root, actual)) fail('Link escapes repository');
      const key = relative(root, target).split(sep).join('/');
      targetPage = pages.get(key);
      if (!targetPage) {
        const encoded = key
          .split('/')
          .map((part) =>
            encodeURIComponent(part).replace(
              /[!'()*]/g,
              (c) => '%' + c.charCodeAt(0).toString(16).toUpperCase(),
            ),
          )
          .join('/');
        const raw = image || /\.(png|webp|jpe?g|gif|svg|zip)$/i.test(key);
        const kind = raw ? 'raw' : (await stat(actual)).isDirectory() ? 'tree' : 'blob';
        return web + '/' + kind + '/' + ref + '/' + encoded + query + fragment;
      }
      if (!path && !fragment && !query) fail('Empty link');
    }
    if (
      fragment &&
      fragment !== '#' &&
      !targetPage.anchors.has(decodeURIComponent(fragment.slice(1)))
    )
      fail('Unknown section on ' + targetPage.slug);
    return web + '/wiki/' + targetPage.slug + query + fragment;
  }
  for (const page of pages.values()) {
    const { source, tree } = page,
      edits = [];
    for (const node of walk(tree)) {
      if (node.type === 'html') {
        const html = source.slice(node.position.start.offset, node.position.end.offset);
        // Handle quoted HTML destinations in prose, ignoring comments.
        if (html.trimStart().startsWith('<!--')) continue;
        for (const match of html.matchAll(/\b(?:href|src)\s*=\s*(["'])(.*?)\1/gi)) {
          const url = await urlFor(
            match[2],
            page,
            node.position.start.line,
            /^src/i.test(match[0]),
          );
          if (url !== match[2]) {
            const start = node.position.start.offset + match.index + match[0].indexOf(match[1]) + 1;
            edits.push([start, start + match[2].length, url]);
          }
        }
      }
      if (!['link', 'image', 'definition'].includes(node.type)) continue;
      const url = await urlFor(node.url, page, node.position.start.line, node.type === 'image');
      if (url === node.url) continue;
      const range = destinationRange(source, node);
      if (!range)
        throw Error(
          page.path + ':' + node.position.start.line + ': unsupported link syntax: ' + node.url,
        );
      edits.push([...range, url]);
    }
    let text = source;
    for (const [start, end, value] of edits.sort((a, b) => b[0] - a[0]))
      text = text.slice(0, start) + value + text.slice(end);
    files.set(page.slug + '.md', marker + page.path + '; edit the source instead. -->\n\n' + text);
  }
  return files;
}

/** Names are preflighted before any mutation. Unrelated pages, files and directories are never removed. */
export async function writeWiki(files, output, { check = false } = {}) {
  if (!check) await mkdir(output, { recursive: true });
  const entries = await readdir(output, { withFileTypes: true });
  const existing = new Map();
  for (const entry of entries) {
    const key = entry.name.toLowerCase();
    if (existing.has(key) && [...files.keys()].some((name) => name.toLowerCase() === key))
      throw Error('Wiki filename conflict: ' + entry.name);
    existing.set(key, entry);
  }
  const changes = [],
    stale = [];
  for (const [name, content] of files) {
    const entry = existing.get(name.toLowerCase());
    if (entry) {
      if (entry.name !== name || !entry.isFile())
        throw Error('Wiki filename conflict: ' + entry.name);
      const text = await readFile(join(output, name), 'utf8');
      if (text === content) continue;
      if (!text.startsWith(marker))
        throw Error('Refusing to overwrite unmanaged wiki page: ' + name);
    }
    changes.push(name);
  }
  for (const entry of entries) {
    if (
      entry.isFile() &&
      entry.name.endsWith('.md') &&
      !files.has(entry.name) &&
      (await readFile(join(output, entry.name), 'utf8')).startsWith(marker)
    )
      stale.push(entry.name);
  }
  if (check && (changes.length || stale.length))
    throw Error('Wiki output is out of date: ' + [...changes, ...stale].join(', '));
  for (const name of changes)
    await writeFile(join(output, name), files.get(name), {
      flag: existing.has(name.toLowerCase()) ? 'w' : 'wx',
    });
  for (const name of stale) await rm(join(output, name));
  return { pages: files.size, written: changes.length, removed: stale.length };
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  try {
    const { values } = parseArgs({
      options: {
        output: { type: 'string' },
        repo: { type: 'string' },
        ref: { type: 'string' },
        check: { type: 'boolean' },
        help: { type: 'boolean' },
      },
    });
    if (values.help)
      console.log(
        'node scripts/wiki.mjs [--output <directory>] [--ref <commit-or-main>] [--repo owner/name] [--check]\n--check validates links; with --output it also compares the rendered files.',
      );
    else {
      const files = await renderWiki(values);
      if (values.check && !values.output) console.log('Validated ' + files.size + ' wiki pages.');
      else {
        const output = resolve(values.output ?? join(sourceRoot, 'output/wiki'));
        let ancestor = output;
        while (
          !(await stat(ancestor).catch((error) => {
            if (error.code !== 'ENOENT' || ancestor === dirname(ancestor)) throw error;
            return undefined;
          }))
        )
          ancestor = dirname(ancestor);
        const actual = resolve(await realpath(ancestor), relative(ancestor, output));
        if (
          actual === resolve(sourceRoot) ||
          inRoot(resolve(sourceRoot, 'docs'), actual) ||
          inRoot(resolve(sourceRoot, '.git'), actual)
        )
          throw Error('Choose a separate wiki output directory');
        console.log(JSON.stringify(await writeWiki(files, output, { check: values.check })));
      }
    }
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
